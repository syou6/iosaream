import Foundation

public struct CharacterId: Hashable, Codable, Sendable, RawRepresentable {
    public let rawValue: String

    public init(rawValue: String) {
        self.rawValue = rawValue
    }

    public init(_ rawValue: String) {
        self.rawValue = rawValue
    }
}

public extension CharacterId {
    static let defaultBuiltin = CharacterId("default")
}
